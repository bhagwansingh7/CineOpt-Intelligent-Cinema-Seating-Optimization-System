"""Regenerates database/seed.sql (demo users, one theatre, seats, some bookings).

    python3 database/generate_seed.py

Passwords are bcrypt hashes created here, never stored in plain text in the SQL.
Demo logins:  admin@cineopt.com / Admin@123   alice@example.com / User@123   bob@example.com / User@123
Needs the `bcrypt` package (pip install bcrypt) or Python's built-in crypt module (Python < 3.13, Linux).
"""
import os
import random

ROWS, COLS = 12, 18
USERS = [("Admin User", "admin@cineopt.com", "Admin@123", "admin"),
         ("Alice Rao", "alice@example.com", "User@123", "user"),
         ("Bob Sen", "bob@example.com", "User@123", "user")]


def hash_password(password: str) -> str:
    try:
        import bcrypt
        return bcrypt.hashpw(password.encode(), bcrypt.gensalt(10)).decode()
    except ImportError:
        import crypt
        return crypt.crypt(password, crypt.mksalt(crypt.METHOD_BLOWFISH, rounds=1 << 10))


def seat_type_and_price(row: int, col: int):
    edge = col <= 2 or col > COLS - 2
    if row <= 3:
        return "standard", 200
    if row <= 9:
        return ("standard", 200) if edge else ("premium", 300)
    return ("premium", 300) if edge else ("recliner", 450)


def main() -> None:
    rng = random.Random(2026)
    seats, booked = [], set()
    sid = 0
    for row in range(1, ROWS + 1):
        for col in range(1, COLS + 1):
            sid += 1
            stype, price = seat_type_and_price(row, col)
            seats.append((sid, row, col, f"{chr(64 + row)}{col}", stype, price))
    # booked: a few groups of 2-4 friends plus scattered single seats (~25% overall)
    while len(booked) < int(0.25 * len(seats)):
        row, col = rng.randint(1, ROWS), rng.randint(1, COLS)
        size = rng.choice([1, 1, 2, 3, 4])
        for c in range(col, min(COLS, col + size - 1) + 1):
            booked.add((row - 1) * COLS + c)
    price = {s[0]: s[5] for s in seats}
    label = {s[0]: s[3] for s in seats}

    # three demo bookings made out of already-booked seats
    ordered = sorted(booked)
    demo = [(2, ordered[10:13], "genetic", 91.20), (3, ordered[40:44], "greedy", 84.75), (2, ordered[60:62], "manual", None)]

    out = ["-- Generated by database/generate_seed.py - demo data for CineOpt", "USE cineopt;", ""]
    out.append("INSERT INTO users (id, name, email, password, role) VALUES")
    out.append(",\n".join(f"({i}, '{n}', '{e}', '{hash_password(p)}', '{r}')" for i, (n, e, p, r) in enumerate(USERS, 1)) + ";")
    out.append("")
    out.append(f"INSERT INTO theatres (id, name, `rows`, `columns`) VALUES (1, 'CineOpt Grand Hall', {ROWS}, {COLS});")
    out.append("")
    out.append("INSERT INTO seats (id, theatre_id, `row_number`, seat_number, seat_label, x_coordinate, y_coordinate, price, seat_type, status) VALUES")
    rows_sql = [f"({i}, 1, {r}, {c}, '{lab}', {c}, {r}, {p}, '{t}', '{'booked' if i in booked else 'available'}')"
                for (i, r, c, lab, t, p) in seats]
    out.append(",\n".join(rows_sql) + ";")
    out.append("")
    out.append("INSERT INTO bookings (id, user_id, theatre_id, total_price, algorithm_used, fitness_score, created_at) VALUES")
    b_sql, bs_sql = [], []
    for n, (uid, ids, algo, fit) in enumerate(demo, 1):
        total = sum(price[i] for i in ids)
        b_sql.append(f"({n}, {uid}, 1, {total}, '{algo}', {fit if fit is not None else 'NULL'}, '2026-09-{20 + n:02d} 18:{10 * n:02d}:00')")
        bs_sql += [f"({n}, {i})" for i in ids]
    out.append(",\n".join(b_sql) + ";")
    out.append("")
    out.append("INSERT INTO booking_seats (booking_id, seat_id) VALUES")
    out.append(",\n".join(bs_sql) + ";")
    out.append("")
    out.append("INSERT INTO booking_requests (user_id, theatre_id, people_count, max_budget, preferred_region, togetherness_weight, preference_weight) VALUES")
    out.append("(2, 1, 3, 1000, 'center', 0.90, 0.80),\n(3, 1, 4, 1500, 'back', 0.70, 0.60);")
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "seed.sql")
    with open(path, "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"seed.sql written: {len(seats)} seats, {len(booked)} booked")


if __name__ == "__main__":
    main()
